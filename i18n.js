const weekdayLabelsByLanguage = {
  "zh-Hant": ["日", "一", "二", "三", "四", "五", "六"],
  "zh-Hans": ["日", "一", "二", "三", "四", "五", "六"],
  en: ["S", "M", "T", "W", "T", "F", "S"],
};

function t(key, values = {}) {
  const dictionary = translations[state.language] || translations[defaultLanguage];
  const template = dictionary[key] || translations[defaultLanguage][key] || key;
  const text = typeof template === "function" ? template(values) : template;
  return Object.entries(values).reduce(
    (result, [name, value]) => result.replaceAll(`{${name}}`, value),
    text,
  );
}

function getLanguageLocale() {
  return {
    "zh-Hant": "zh-Hant-TW",
    "zh-Hans": "zh-Hans-CN",
    en: "en-US",
  }[state.language] || "zh-Hant-TW";
}

function getWeekdayLabels() {
  return weekdayLabelsByLanguage[state.language] || weekdayLabelsByLanguage[defaultLanguage];
}

function getDefaultSymbolMeanings(language = state.language) {
  return defaultSymbolMeaningsByLanguage[language] || defaultSymbolMeaningsByLanguage[defaultLanguage];
}
